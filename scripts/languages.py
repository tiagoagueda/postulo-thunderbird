"""Write the list of languages the extension ships, from the core's roll-out.

    python scripts/languages.py            # rewrite src/lib/languages.js
    python scripts/languages.py --check    # fail if that file is not what the core says

Postulo's roll-out is the core's `src/postulo/locale/status.json`. This extension follows the
core release it is released beside: every language the core has a catalogue for, in draft,
English included. `en-GB`, the
source, has no row there and is always in. An administrator's narrowing of a site's list
plays no part, and neither does how far a catalogue has got; the extension carries all its
keys in every language at once, as drafts (test/i18n.test.mjs).

It reads the core from the checkout beside this one (`../postulo`), where the Postulo
workspace keeps it (or from `POSTULO_CORE`, for a checkout kept elsewhere), and imports `core/languages.py` for the own names and the direction
(that module needs no Django). The list is committed, so building and testing the extension
need neither Python nor the core; only a new core release does.

The core's codes become the extension's here and nowhere else: the four spelled differently
are in `SPELLED`, every other code is kept as it is, and a code with a region or a script
that has no entry stops the script rather than being guessed at.
"""

from __future__ import annotations

import importlib.util
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
CORE = Path(os.environ.get("POSTULO_CORE") or HERE.parent / "postulo")
OUT = HERE / "src" / "lib" / "languages.js"

#: core code -> (folder under _locales, BCP 47 tag the catalogue says). The region is dropped
#: where the core has one variety of a language, kept where it has two (pt-BR, pt-PT). A
#: folder is named by language and region with an underscore and never by script, so
#: Serbian's is `sr` and its tag `sr-Cyrl`.
SPELLED = {
    "en-GB": ("en", "en"),
    "fr-FR": ("fr", "fr"),
    "pt-PT": ("pt_PT", "pt-PT"),
    "pt-BR": ("pt_BR", "pt-BR"),
    "sr-Cyrl": ("sr", "sr-Cyrl"),
    # Weblate names these folders after the code, with an underscore; the WebExtension format
    # has no folder for a script, so zh_Hans and zh_Hant are Weblate's, and the tag is the core's.
    "en-CA": ("en_CA", "en-CA"),
    "es-MX": ("es_MX", "es-MX"),
    "fr-CA": ("fr_CA", "fr-CA"),
    "zh-Hans": ("zh_Hans", "zh-Hans"),
    "zh-Hant": ("zh_Hant", "zh-Hant"),
    # Weblate's Norwegian Bokmål is nb_NO; it has no plain nb.
    "nb": ("nb_NO", "nb"),
}

HEADER = """\
// The languages the extension ships, each with the folder it lives in under _locales, its BCP 47
// tag as the catalogue's `languageTag` says it, its direction and its own name, as Postulo's
// picker shows it (the core's NATIVE_NAMES). A language is named in itself so that somebody
// who cannot read the page's present language can still find theirs.
//
// GENERATED by scripts/languages.py from the core's roll-out; do not edit by hand.
// test/i18n.test.mjs keeps this list and the folders in step.

export const LANGUAGES = [
"""


def core_languages():
    """The core's `core/languages.py`, loaded from the sibling checkout."""
    path = CORE / "src" / "postulo" / "core" / "languages.py"
    if not path.exists():
        raise SystemExit(f"The core is not checked out at {CORE}; the roll-out lives there.")
    spec = importlib.util.spec_from_file_location("postulo_languages", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses look their module up here
    spec.loader.exec_module(module)
    return module


def started(core) -> list[str]:
    """The source, then every code the core has a catalogue for, started or not.

    The Thunderbird extension follows the core's whole roll-out, not only the languages with a
    translation: Weblate holds a catalogue for each (postulo-chromium ships only the started ones).
    """
    status = json.loads((CORE / "src" / "postulo" / "locale" / "status.json").read_text("utf-8"))
    codes = [core.SOURCE] + list(status)
    unknown = [code for code in codes if code not in core.NATIVE_NAMES]
    if unknown:
        raise SystemExit(f"The core started {unknown} but has no own name for them.")
    return codes


def spelled(code: str) -> tuple[str, str]:
    """(folder, tag) for a core code."""
    if code in SPELLED:
        return SPELLED[code]
    if "-" in code or "_" in code:
        raise SystemExit(f"{code} has a region or a script and no entry in SPELLED; add one.")
    return code, code


def rendered() -> str:
    core = core_languages()
    rows = sorted((*spelled(code), core.direction(code), core.NATIVE_NAMES[code]) for code in started(core))
    folders = [row[0] for row in rows]
    if len(set(folders)) != len(folders):
        raise SystemExit("Two core codes would share a folder.")
    lines = [
        f'  {{ folder: "{folder}", tag: "{tag}", direction: "{direction}", name: {json.dumps(name, ensure_ascii=False)} }},\n'
        for folder, tag, direction, name in rows
    ]
    return HEADER + "".join(lines) + "];\n"


def main() -> None:
    text = rendered()
    if "--check" in sys.argv[1:]:
        if OUT.read_text("utf-8") != text:
            raise SystemExit(f"{OUT.relative_to(HERE)} differs from the core's roll-out; run scripts/languages.py.")
        print("languages.js matches the core")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(HERE)}  {text.count('folder:')} languages")


if __name__ == "__main__":
    main()
